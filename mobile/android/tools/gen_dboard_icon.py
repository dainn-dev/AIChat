"""Generate the DBoard launcher icon: a yellow "D" on black with a small keyboard inside the D.

Writes, for each build type (debug, beta, stable), the adaptive icon's foreground and monochrome vector drawables
into app/src/main/res/drawable/. The background is the color resource ic_app_icon_background (#000000).

Usage (from mobile/android/):
    python tools/gen_dboard_icon.py

Geometry is in the 834 x 834 space of the original logo artwork (stroke 100, D spans x 199..634, y 173..660).
The artwork is scaled down inside the adaptive icon so every corner stays inside the 66 dp safe zone circle.
"""
from pathlib import Path

YELLOW = "#FFFCD401"
MONO = "#FF000000"  # themed icons only use the alpha of this layer

# D outline: outer radius 243.5 and inner radius 143.5 around (390.5, 416.5); the left side is open (the notch
# between y 460 and 560), as in the artwork.
D_PATH = (
    "M199,173 H390.5 A243.5,243.5 0 0 1 390.5,660 H199 V560 H390.5 "
    "A143.5,143.5 0 0 0 390.5,273 H299 V460 H199 Z"
)

# Keyboard inside the D's counter: three rows of three keys and a space bar.
KEY_SIZE = 44.0
KEY_GAP = 8.0
KEY_RADIUS = 10.0
KEYBOARD_LEFT = 318.0
KEYBOARD_TOP = 317.0
COLUMNS = 3
LETTER_ROWS = 3

# 834 artwork units -> 108 dp. Scale 0.78 keeps the D's far corners (327 units from the center) within the
# 66 dp safe zone (0.78 * 327 = 255 <= 254.3 units).
CANVAS = 834.0
ART_SCALE = 0.78


def rounded_rect(x: float, y: float, w: float, h: float, r: float) -> str:
    return (
        f"M{x + r:g},{y:g} H{x + w - r:g} Q{x + w:g},{y:g} {x + w:g},{y + r:g} "
        f"V{y + h - r:g} Q{x + w:g},{y + h:g} {x + w - r:g},{y + h:g} "
        f"H{x + r:g} Q{x:g},{y + h:g} {x:g},{y + h - r:g} "
        f"V{y + r:g} Q{x:g},{y:g} {x + r:g},{y:g} Z"
    )


def keyboard_path() -> str:
    pitch = KEY_SIZE + KEY_GAP
    width = COLUMNS * KEY_SIZE + (COLUMNS - 1) * KEY_GAP
    parts = []
    for row in range(LETTER_ROWS):
        for col in range(COLUMNS):
            parts.append(
                rounded_rect(KEYBOARD_LEFT + col * pitch, KEYBOARD_TOP + row * pitch, KEY_SIZE, KEY_SIZE, KEY_RADIUS)
            )
    parts.append(rounded_rect(KEYBOARD_LEFT, KEYBOARD_TOP + LETTER_ROWS * pitch, width, KEY_SIZE, KEY_RADIUS))
    return " ".join(parts)


def vector(color: str) -> str:
    center = CANVAS / 2
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_dboard_icon.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="{CANVAS:g}"
    android:viewportHeight="{CANVAS:g}">
  <group
      android:pivotX="{center:g}"
      android:pivotY="{center:g}"
      android:scaleX="{ART_SCALE:g}"
      android:scaleY="{ART_SCALE:g}">
    <path
        android:fillColor="{color}"
        android:pathData="{D_PATH}"/>
    <path
        android:fillColor="{color}"
        android:pathData="{keyboard_path()}"/>
  </group>
</vector>
"""


def main() -> None:
    drawable_dir = Path("app/src/main/res/drawable")
    for build_type in ("debug", "beta", "stable"):
        (drawable_dir / f"ic_app_icon_{build_type}_foreground.xml").write_text(
            vector(YELLOW), encoding="utf-8", newline="\n"
        )
        (drawable_dir / f"ic_app_icon_{build_type}_monochrome.xml").write_text(
            vector(MONO), encoding="utf-8", newline="\n"
        )
    print("wrote 6 drawables")


if __name__ == "__main__":
    main()
