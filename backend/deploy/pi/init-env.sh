#!/usr/bin/env sh
# Creates ~/aichat/.env for the Pi deployment, with fresh random secrets generated on the Pi itself.
# Refuses to overwrite an existing .env (that would orphan the database password).
# Usage: sh init-env.sh   (from the directory that holds compose.yml)
set -eu

ENV_FILE=".env"

if [ -e "$ENV_FILE" ]; then
  echo "$ENV_FILE already exists; not touching it." >&2
  exit 1
fi

random_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  else
    od -An -N32 -tx1 /dev/urandom | tr -d ' \n'
  fi
}

umask 077
cat > "$ENV_FILE" <<EOF
# AIChat backend, Raspberry Pi production. Generated by init-env.sh. Keep private (chmod 600).
NODE_ENV=production
PORT=3000
# Native clients send no Origin header; only browser callers are subject to CORS.
CORS_ORIGINS=https://chat-api.dainn.online

# Database: the compose service "db" (not exposed on the host).
DATABASE_HOST=db
DATABASE_PORT=5432
DATABASE_USER=aichat
DATABASE_PASSWORD=$(random_hex)
DATABASE_NAME=aichat
DATABASE_SSL=false

# Auth
JWT_ACCESS_SECRET=$(random_hex)
JWT_ACCESS_TTL=15m
REFRESH_TOKEN_TTL_DAYS=30
BCRYPT_ROUNDS=10

# LLM: fill in LLM_API_KEY, then: docker compose up -d api
# Empty key = keyless stub provider (deterministic fake replies, embeddings disabled for real use).
LLM_API_KEY=
# LLM_BASE_URL=
# LLM_REPLY_MODEL=
# LLM_ANALYSIS_MODEL=
LLM_REQUEST_TIMEOUT_MS=30000
LLM_MAX_REPAIR_RETRIES=1
EMBEDDING_DIMENSIONS=1536

# Memory engine (Redis is the compose service "redis")
MEMORY_RETRIEVAL_ENABLED=true
MEMORY_EXTRACTION_ENABLED=true
REDIS_HOST=redis
REDIS_PORT=6379

# Usage / quota
USAGE_FREE_REPLIES_PER_DAY=20
USAGE_FREE_SCREENSHOTS_PER_DAY=5
USAGE_PRO_DAILY_SPEND_CAP_USD=20

# Optional integrations (blank = disabled / degraded mode)
S3_REGION=us-east-1
S3_BUCKET=aichat-screenshots
S3_ACCESS_KEY_ID=
S3_SECRET_ACCESS_KEY=
SENTRY_DSN=
POSTHOG_API_KEY=
EOF
chmod 600 "$ENV_FILE"
echo "Created $ENV_FILE with new random DATABASE_PASSWORD and JWT_ACCESS_SECRET. Add LLM_API_KEY when ready."
